export const KEYWORD_DICT = RAW
  .split('\n')
  .filter((line) => !line.trim().startsWith('#'))
  .join('，')
  .split(/[，,\s]+/)
  .map((s) => s.trim())
  .filter(Boolean);

/** 泛类词：它们几乎什么都命中，**不能单独当关键字**（写进备注等于没写） */
const GENERIC_SET = new Set(['交通', '餐饮', '购物', '消费', '充值', '服务']);

/**
 * 商品说明里命中的词表词（按词表顺序，最多两个）。
 *
 * 两条自定规则（用户 2026-11-08 的「靠前两个」落地版）：
 *   · 命中的两个词如果共享字符（竖笛 / 笛子、流量卡 / 流量），只留靠前的那个 ——
 *     它们是同一样东西的两种叫法，写两遍没有信息量；
 *   · 只命中泛类词（服务 / 消费 / 购物）时返回空 —— 这种词区分不了任何流水。
 */
export function dictHits(text) {
  const t = String(text == null ? '' : text);
  if (!t) return [];
  const hits = [];
  for (const w of KEYWORD_DICT) {
    if (!t.includes(w)) continue;
    const dup = hits.some((h) => [...h].some((ch) => w.includes(ch)));
    if (!dup) hits.push(w);
    if (hits.length >= 2) break;
  }
  if (hits.every((h) => GENERIC_SET.has(h))) return [];
  return hits;
}
