/**
 * 关键字词表
 * 层：第一层 · core
 *
 * 用户 2026-11-08：「做一张有优先顺序的词表。如果一堆词都在词表里出现，
 * 只需靠前的两个。词表是按特例性排序的，越靠前越能精确具象对象。」
 *
 * 写法也按用户的要求：**不用引号，中文逗号隔开**，一行一档 ——
 * 顺序即优先级，加词就插一行。
 *
 *   竖笛 内裤 流量卡 这类具体物品在最前；
 *   地铁 咖啡 电费 这类场景居中；
 *   交通 餐饮 购物 这类泛类词在最后（只有前面全没命中才会轮到）。
 */

